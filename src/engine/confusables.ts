/**
 * 혼동문자(homoglyph) 폴딩 테이블 — UTS #39 confusables 중 리딩방 유인글에서 실제로 쓰이는 부분집합.
 * 키릴/그리스/기타 → 라틴. 전각·수학기호·원문자 등은 NFKC가 처리하므로 여기 없음.
 * 순서 주의: 이 테이블은 NFD 직후, NFKC 이전에 적용된다 (UTS #39 skeleton 순서).
 */
export const CONFUSABLES: Record<string, string> = {
  // Cyrillic → Latin
  "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x", "к": "k",
  "н": "h", "м": "m", "т": "t", "в": "b", "і": "i", "ј": "j", "ѕ": "s", "ԁ": "d",
  "ɡ": "g", "ԛ": "q", "ԝ": "w", "ӏ": "l", "ь": "b", "г": "r", "п": "n", "л": "n",
  "А": "A", "Е": "E", "О": "O", "Р": "P", "С": "C", "У": "Y", "Х": "X", "К": "K",
  "Н": "H", "М": "M", "Т": "T", "В": "B", "І": "I", "Ј": "J", "Ѕ": "S",
  // Greek → Latin
  "α": "a", "β": "b", "ε": "e", "ι": "i", "κ": "k", "ν": "v", "ο": "o", "ρ": "p",
  "τ": "t", "υ": "u", "χ": "x", "γ": "y", "Α": "A", "Β": "B", "Ε": "E", "Ζ": "Z",
  "Η": "H", "Ι": "I", "Κ": "K", "Μ": "M", "Ν": "N", "Ο": "O", "Ρ": "P", "Τ": "T",
  "Υ": "Y", "Χ": "X",
  // Latin lookalikes / symbols
  "ſ": "f", "ı": "i", "ł": "l", "ø": "o", "đ": "d", "ħ": "h", "ŧ": "t",
  "|": "l", "!": "i", "$": "s", "@": "a", "0": "o", "1": "l", "3": "e", "5": "s", "7": "t",
  // 한글 유사 특수문자
  "ㅇ": "ㅇ", "０": "0",
};

/** 문자 하나를 폴딩. 매핑 없으면 원문 반환 */
export function foldChar(ch: string): string {
  return CONFUSABLES[ch] ?? ch;
}

/** 숫자→문자 폴딩은 "글자 사이에 낀 숫자"일 때만 의미가 있어 별도 처리 */
export const DIGIT_LOOKALIKES = new Set(["0", "1", "3", "5", "7", "!", "|", "$", "@"]);
