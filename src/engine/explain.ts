/**
 * 근거 코드 → 사람이 읽는 설명.
 *
 * 화면은 "사기다/의심된다" 라고 말하지 않는다. 대신 **무엇이 감지됐고, 그것이 왜 신호가 되며,
 * 실제 유인글에서는 어떻게 쓰이고, 정상적인 글에서는 어떻게 보이는지** 를 길게 풀어 준다.
 * 판단은 읽는 사람이 한다.
 *
 * 브라우저 번들에 포함되므로 node 모듈을 import 하지 않는다.
 */
import { TERMS, PATTERNS, type Category } from "./lexicon";

export interface Explanation {
  /** 이 글에서 무엇이 감지됐나 */
  what: string;
  /** 왜 이것이 신호가 되나 (실제 수법) */
  why: string;
  /** 실제 유인글에서 이렇게 쓰인다 — 예시 문장 */
  example: string;
  /** 정상적인 글에서는 이렇게 쓰인다 — 신호가 아닐 때 */
  benign: string;
}

export type ExplainCategory = Category | "structure" | "account" | "context" | "review";

const TERM_BY_NAME = new Map(TERMS.map((t) => [t.term, t]));
const PATTERN_BY_LABEL = new Map(PATTERNS.map((p) => [p.label, p]));

/** 근거 코드가 어느 범주에 속하는지. 어휘는 사전에서, 구조 신호는 패턴 표에서 찾는다 */
export function categoryOf(code: string): ExplainCategory {
  if (code.startsWith("term:")) return TERM_BY_NAME.get(code.slice(5))?.cat ?? "invest";
  if (code.startsWith("pattern:")) return PATTERN_BY_LABEL.get(code.slice(8))?.cat ?? "structure";
  if (code.startsWith("impersonate:")) return "impersonate";
  if (code.startsWith("evidence:")) return "impersonate";
  if (code.startsWith("identity:")) return "account";
  if (code.startsWith("combo:") || code === "obfuscation" || code === "cta") return "structure";
  if (code.startsWith("acct:") || code === "cluster" || code === "spread" || code === "spray" || code === "shared-contact") return "account";
  if (code === "counter" || code.startsWith("veto:") || code.startsWith("gate:")) return "context";
  if (code.startsWith("llm:")) return "review";
  return "structure";
}

