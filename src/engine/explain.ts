/**
 * 근거 코드 하나에 대한 설명. 특정 코드 → 패턴 → 범주 순으로 찾고, 어떤 경우에도 빈 값을 돌려주지 않는다.
 */
export function explainReason(code: string, label: string, evidence?: string): Explanation {
  const ev = evidence?.trim() || undefined;
  const specific = SPECIFIC[code];
  if (specific) return specific(label, ev);
  if (code.startsWith("pattern:")) {
    const p = PATTERN_TEXT[code];
    if (p) return p(label, ev);
  }
  if (code.startsWith("veto:")) {
    return {
      what: `자동으로 강한 신호에 올리지 않는 맥락이 감지됐습니다(${label}${ev ? `, "${ev}"` : ""}). 점수 상한을 낮춥니다.`,
      why: `합법 광고·기사·공공 캠페인·풍자·해명처럼 보이는 형식이 하나라도 있으면, 자동 분류를 포기하고 사람이 보는 쪽이 항상 안전합니다.`,
      example: `유인 어휘가 많지만 출처 표기나 고지문이 붙은 글.`,
      benign: `이 항목은 신호를 지우는 것이 아니라 상한을 두는 것입니다. 다른 항목은 그대로 남습니다.`,
    };
  }
  if (code.startsWith("gate:")) return SPECIFIC["gate:no-contact"](label, ev);
  if (code.startsWith("llm:")) return SPECIFIC[code.startsWith("llm:scam") ? "llm:scam" : "llm:benign"](label, ev);
  if (code.startsWith("impersonate:")) return CATEGORY_TEXT.impersonate(label, ev);
  if (code.startsWith("term:")) {
    const t = TERM_BY_NAME.get(code.slice(5));
    if (t?.sub === "institution") return INSTITUTION(label, ev);
    if (t?.sub === "credential") return CREDENTIAL(label, ev);
    return CATEGORY_TEXT[t?.cat ?? "invest"](label, ev);
  }
  const cat = categoryOf(code);
  if (cat in CATEGORY_TEXT) return CATEGORY_TEXT[cat as Category](label, ev);
  return {
    what: `${label}${ev ? ` ("${ev}")` : ""}`,
    why: `이 항목은 점수 계산에 반영된 신호입니다. 다른 항목과 함께 읽어 주세요.`,
    example: `-`,
    benign: `단독으로는 분류를 바꾸지 않습니다.`,
  };
}

/** 근거 목록에 설명을 붙인다 (리포트 JSON·화면 공용) */
export function explainReasons<T extends { code: string; label: string; evidence?: string }>(reasons: T[]): (T & Explanation)[] {
  return reasons.map((r) => ({ ...r, ...explainReason(r.code, r.label, r.evidence) }));
}
