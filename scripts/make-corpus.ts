const rows: Row[] = [];
let n = 0;
const push = (label: "scam" | "benign", [text, note, author, tf]: Spec) => {
  n++;
  rows.push({
    id: `${label === "scam" ? "s" : "b"}${String(n).padStart(3, "0")}`,
    text: tf ? tf(text) : text,
    label,
    note,
    ...(author ? { author } : {}),
  });
};
for (const s of SCAM) push("scam", s);
n = 0;
for (const b of BENIGN) push("benign", b);

// 난독화 계열을 코퍼스 전반에 고루 퍼뜨리기 위해, 일부 scam 문구에 추가 변형본을 만든다.
const EXTRA_TF: { tf: (s: string) => string; note: string }[] = [
  { tf: chosung, note: "초성 변형본" },
  { tf: zeroWidth, note: "제로폭 변형본" },
  { tf: separators, note: "구분자 변형본" },
  { tf: homoglyph, note: "혼동문자 변형본" },
];
let k = 0;
for (let i = 0; i < SCAM.length; i += 2) {
  const [text, note, author] = SCAM[i];
  const { tf, note: tn } = EXTRA_TF[k % EXTRA_TF.length];
  k++;
  rows.push({ id: `sx${String(k).padStart(3, "0")}`, text: tf(text), label: "scam", note: `${note} / ${tn}`, ...(author ? { author } : {}) });
}

const outDir = join(process.cwd(), "eval");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "corpus.jsonl"), rows.map((r) => JSON.stringify(r)).join("\n") + "\n", "utf8");

