const ZW = "​";
const CHOSUNG_MAP: Record<string, string> = {
  텔레그램: "ㅌㄹㄱㄹ",
  오픈채팅: "ㅇㅍㅊㅌ",
  리딩방: "ㄹㄷㅂ",
  종목추천: "ㅈㅁㅊㅊ",
  수익인증: "ㅅㅇㅇㅈ",
};
function chosung(s: string): string {
  let out = s;
  for (const [k, v] of Object.entries(CHOSUNG_MAP)) out = out.split(k).join(v);
  return out;
}
function zeroWidth(s: string): string {
  // 앞쪽 한글 토큰 하나에만 제로폭을 끼운다
  return s.replace(/([가-힣]{3,})/, (m) => Array.from(m).join(ZW));
}
function separators(s: string): string {
  return s.replace(/([가-힣]{3,})/, (m) => Array.from(m).join("."));
}
const CYR: Record<string, string> = { a: "а", e: "е", o: "о", p: "р", c: "с", x: "х", y: "у", T: "Т" };
function homoglyph(s: string): string {
  return s.replace(/[Taeopcxy]/g, (c) => CYR[c] ?? c);
}
function fullwidth(s: string): string {
  return s.replace(/[!-~]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0xfee0));
}
function leet(s: string): string {
  return s.replace(/telegram/gi, "te1egram").replace(/kakao/gi, "kak4o");
}

